// Tìm câu chữ cần đọc lại; kết quả không dùng để suy ra tác giả của file.
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const folders = ["src", "scripts", "docs", "database", "agent-skills"];
const singleFiles = ["README.md", "CLAUDE.md", "CHAY-WEB.bat", "next.config.ts", "eslint.config.mjs"];
const extensions = new Set([".ts", ".tsx", ".js", ".mjs", ".md", ".sql", ".css", ".ps1", ".bat"]);
const excludedFolders = new Set(["node_modules", ".next", ".git", "output", "archive", "vendor", "gop-code-voice"]);

const checks = [
  { code: "ASSISTANT_MARKER", pattern: /\b(?:as an ai language model|generated by (?:chatgpt|claude|codex)|this code was generated by ai)\b/i },
  { code: "ASSISTANT_MARKER", pattern: /(?:được tạo bởi|do)\s+(?:chatgpt|claude|codex)\b/i },
  { code: "PLACEHOLDER", pattern: /\b(?:lorem ipsum|coming soon|your project name|todo: implement|insert (?:text|content) here)\b/i },
  { code: "GENERIC_CLAIM", pattern: /(?:trải nghiệm tuyệt vời|giải pháp tối ưu|đáp ứng mọi nhu cầu|hoàn thiện nhất có thể|một cách toàn diện)/i },
  { code: "UI_JARGON", pattern: /\bbản(?: gửi)? v(?:\d+|\$\{|\{)/i },
];

function* walk(location) {
  if (!fs.existsSync(location)) return;
  for (const entry of fs.readdirSync(location, { withFileTypes: true })) {
    if (entry.isDirectory()) {
      if (!excludedFolders.has(entry.name)) yield* walk(path.join(location, entry.name));
    } else if (entry.isFile() && extensions.has(path.extname(entry.name))) {
      yield path.join(location, entry.name);
    }
  }
}

const files = [
  ...singleFiles.map((name) => path.join(root, name)).filter((file) => fs.existsSync(file)),
  ...folders.flatMap((name) => [...walk(path.join(root, name))]),
].filter((file) => file !== path.resolve(import.meta.filename));

const findings = [];
for (const file of files) {
  if (fs.statSync(file).size > 500_000) continue;
  const lines = fs.readFileSync(file, "utf8").split(/\r?\n/);
  let previousComment = "";
  for (let index = 0; index < lines.length; index += 1) {
    const line = lines[index].trim();
    for (const check of checks) {
      if (check.pattern.test(line)) {
        findings.push({ file: path.relative(root, file).replaceAll("\\", "/"), line: index + 1, code: check.code, text: line.slice(0, 160) });
      }
    }
    const comment = /^(?:\/\/|--|#)\s*(.+)$/.exec(line)?.[1]?.trim() ?? "";
    if (comment && comment === previousComment) {
      findings.push({ file: path.relative(root, file).replaceAll("\\", "/"), line: index + 1, code: "REPEATED_COMMENT", text: line.slice(0, 160) });
    }
    previousComment = comment;
  }
}

const summary = Object.fromEntries([...new Set(checks.map((check) => check.code).concat("REPEATED_COMMENT"))]
  .map((code) => [code, findings.filter((item) => item.code === code).length]));

if (process.argv.includes("--json")) {
  process.stdout.write(`${JSON.stringify({ scannedFiles: files.length, summary, findings }, null, 2)}\n`);
} else {
  console.log(`# Ứng viên cần đọc lại: ${files.length} file`);
  console.log("Mẫu từ khóa không chứng minh nguồn gốc AI. Đọc ngữ cảnh trước khi sửa.\n");
  console.log(Object.entries(summary).map(([code, count]) => `${code}: ${count}`).join(" · "));
  for (const item of findings) console.log(`${item.file}:${item.line} [${item.code}] ${item.text}`);
}
